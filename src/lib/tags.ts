import { Transaction } from "@/types/finance";
import { isTransfer } from "@/lib/utils";
import { supabase } from "@/lib/supabase";

export interface TagStat {
  name: string;
  normKey: string;
  count: number;
  totalExpense: number;
  totalIncome: number;
  avgTicket: number;
  categories: string[];
  transactions: Transaction[];
}

export const normalizeTagKey = (raw: string): string =>
  raw
    .trim()
    .replace(/^#+/, "")
    .toLowerCase()
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .replace(/\s+/g, " ")
    .trim();

export const formatTagDisplay = (raw: string): string =>
  raw
    .trim()
    .replace(/^#+/, "")
    .replace(/\s+/g, " ")
    .trim();

const AUTO_DESC_PATTERNS = [
  /^cuota\s+\d+\/\d+/i,
  /\(cuota\s+\d+\/\d+\)/i,
  /^comisi[oó]n apertura:/i,
  /^ingreso de pr[eé]stamo:/i,
  /^neto ajustado\s*\(/i,
  /^autom[aá]tico:/i,
  /^gasto recurrente/i,
  /\(fraccionado\)$/i,
  /^(a|de)\s+[a-záéíóúñ0-9\s]+$/i,
];

export const isAutoGeneratedDescription = (desc?: string | null): boolean => {
  const trimmed = (desc || "").trim();
  if (!trimmed) return false;
  return AUTO_DESC_PATTERNS.some((re) => re.test(trimmed));
};

const QUICK_PREFIX_RE = /^gasto\s+r[aá]pido:\s*/i;

export const hasQuickExpensePrefix = (desc?: string | null): boolean =>
  QUICK_PREFIX_RE.test((desc || "").trim());

export const stripQuickExpensePrefix = (desc?: string | null): string =>
  (desc || "").trim().replace(QUICK_PREFIX_RE, "").trim();

const isRedundantWithCategory = (tagNorm: string, category: string): boolean => {
  const catNorm = normalizeTagKey(category);
  if (!tagNorm) return true;
  if (tagNorm === catNorm) return true;
  if (catNorm === "supermercado" && (tagNorm === "compra" || tagNorm === "compras")) return true;
  return false;
};

/**
 * Extracts effective tags from a transaction:
 * 1) Explicit `tx.tags` if present.
 * 2) Otherwise derives clean tag(s) from non-auto `tx.description` (stripping legacy "Gasto rápido: ").
 */
export const extractTransactionTags = (tx: Transaction): string[] => {
  if (isTransfer(tx.category)) return [];

  if (Array.isArray(tx.tags) && tx.tags.length > 0) {
    const unique = new Map<string, string>();
    for (const raw of tx.tags) {
      const display = formatTagDisplay(raw);
      const norm = normalizeTagKey(display);
      if (norm && !unique.has(norm)) {
        unique.set(norm, display);
      }
    }
    return Array.from(unique.values());
  }

  const rawDesc = (tx.description || "").trim();
  if (!rawDesc || isAutoGeneratedDescription(rawDesc)) return [];

  const cleaned = stripQuickExpensePrefix(rawDesc);
  if (!cleaned) return [];

  // If the description is short comma-separated items (up to 4 parts, each <= 36 chars), split into tags
  const parts = cleaned.includes(",")
    ? cleaned.split(",").map((p) => formatTagDisplay(p)).filter(Boolean)
    : [formatTagDisplay(cleaned)];

  const useParts = parts.length <= 4 && parts.every((p) => p.length <= 36) ? parts : [cleaned];

  const unique = new Map<string, string>();
  for (const p of useParts) {
    const norm = normalizeTagKey(p);
    if (!norm || isRedundantWithCategory(norm, tx.category)) continue;
    if (!unique.has(norm)) unique.set(norm, p);
  }
  return Array.from(unique.values());
};

/**
 * Computes Levenshtein edit distance (for typo-tolerant tag matching, e.g. "almuezo" -> "almuerzo").
 */
export const levenshteinDistance = (a: string, b: string): number => {
  if (a === b) return 0;
  if (!a.length) return b.length;
  if (!b.length) return a.length;

  const dp: number[] = Array.from({ length: b.length + 1 }, (_, i) => i);
  for (let i = 1; i <= a.length; i++) {
    let prev = i - 1;
    dp[0] = i;
    for (let j = 1; j <= b.length; j++) {
      const temp = dp[j];
      const cost = a[i - 1] === b[j - 1] ? 0 : 1;
      dp[j] = Math.min(dp[j] + 1, dp[j - 1] + 1, prev + cost);
      prev = temp;
    }
  }
  return dp[b.length];
};

export const isFuzzyTagMatch = (queryNorm: string, tagNorm: string): { match: boolean; score: number } => {
  if (!queryNorm) return { match: true, score: 100 };
  if (tagNorm === queryNorm) return { match: true, score: 0 };
  if (tagNorm.startsWith(queryNorm)) return { match: true, score: 1 };
  if (tagNorm.includes(queryNorm)) return { match: true, score: 2 };

  // Word-level prefix / fuzzy match (e.g. "almuezo" matches "almuerzo" and "almuerzo trabajo")
  const queryWords = queryNorm.split(" ").filter(Boolean);
  const tagWords = tagNorm.split(" ").filter(Boolean);

  if (queryNorm.length >= 3) {
    const maxDist = queryNorm.length <= 5 ? 1 : 2;
    const allQueryWordsMatch = queryWords.every((qw) =>
      tagWords.some((tw) => {
        if (tw.startsWith(qw) || tw.includes(qw)) return true;
        if (Math.abs(tw.length - qw.length) > maxDist) return false;
        return levenshteinDistance(qw, tw) <= maxDist;
      })
    );
    if (allQueryWordsMatch) return { match: true, score: 3 };

    if (Math.abs(tagNorm.length - queryNorm.length) <= maxDist) {
      const fullDist = levenshteinDistance(queryNorm, tagNorm);
      if (fullDist <= maxDist) return { match: true, score: 3 + fullDist };
    }
  }

  return { match: false, score: 999 };
};

export const computeTagStats = (transactions: Transaction[]): TagStat[] => {
  const map = new Map<
    string,
    {
      displayCounts: Map<string, number>;
      count: number;
      totalExpense: number;
      totalIncome: number;
      categories: Set<string>;
      transactions: Transaction[];
    }
  >();

  for (const tx of transactions) {
    if (tx.isIgnored || isTransfer(tx.category)) continue;
    const tags = extractTransactionTags(tx);
    for (const tag of tags) {
      const norm = normalizeTagKey(tag);
      if (!norm) continue;
      let entry = map.get(norm);
      if (!entry) {
        entry = {
          displayCounts: new Map(),
          count: 0,
          totalExpense: 0,
          totalIncome: 0,
          categories: new Set(),
          transactions: [],
        };
        map.set(norm, entry);
      }
      entry.displayCounts.set(tag, (entry.displayCounts.get(tag) || 0) + 1);
      entry.count++;
      if (tx.type === "expense") entry.totalExpense += tx.amount;
      else entry.totalIncome += tx.amount;
      entry.categories.add(tx.category.trim());
      entry.transactions.push(tx);
    }
  }

  return Array.from(map.entries())
    .map(([normKey, entry]) => {
      // Pick the most frequent capitalization as canonical display name
      let bestName = normKey;
      let bestCount = -1;
      for (const [disp, cnt] of entry.displayCounts.entries()) {
        if (cnt > bestCount) {
          bestCount = cnt;
          bestName = disp;
        }
      }
      const totalAmt = entry.totalExpense + entry.totalIncome;
      return {
        name: bestName,
        normKey,
        count: entry.count,
        totalExpense: Number(entry.totalExpense.toFixed(2)),
        totalIncome: Number(entry.totalIncome.toFixed(2)),
        avgTicket: Number((totalAmt / (entry.count || 1)).toFixed(2)),
        categories: Array.from(entry.categories),
        transactions: entry.transactions.sort((a, b) => b.date.localeCompare(a.date)),
      };
    })
    .sort((a, b) => b.totalExpense - a.totalExpense || b.count - a.count || a.name.localeCompare(b.name));
};

export const suggestMatchingTags = (
  query: string,
  catalog: TagStat[],
  alreadySelected: string[],
  limit = 6
): TagStat[] => {
  const qNorm = normalizeTagKey(query);
  const selectedNorms = new Set(alreadySelected.map(normalizeTagKey));

  const scored = catalog
    .filter((item) => !selectedNorms.has(item.normKey))
    .map((item) => ({ item, ...isFuzzyTagMatch(qNorm, item.normKey) }))
    .filter((r) => r.match)
    .sort((a, b) => a.score - b.score || b.item.count - a.item.count || a.item.name.localeCompare(b.item.name));

  return scored.slice(0, limit).map((r) => r.item);
};

/**
 * Renames or merges an existing tag across all matching transactions in Supabase.
 */
export const renameOrMergeTagInCloud = async (
  sourceNormKey: string,
  targetNameRaw: string,
  transactions: Transaction[]
): Promise<number> => {
  const targetDisplay = formatTagDisplay(targetNameRaw);
  const targetNorm = normalizeTagKey(targetDisplay);
  if (!targetDisplay || !targetNorm) {
    throw new Error("El nombre de la etiqueta destino es obligatorio.");
  }

  let updatedCount = 0;

  for (const tx of transactions) {
    const currentTags = extractTransactionTags(tx);
    if (!currentTags.some((t) => normalizeTagKey(t) === sourceNormKey)) continue;

    const nextUnique = new Map<string, string>();
    for (const t of currentTags) {
      const n = normalizeTagKey(t);
      if (n === sourceNormKey) {
        nextUnique.set(targetNorm, targetDisplay);
      } else if (!nextUnique.has(n)) {
        nextUnique.set(n, t);
      }
    }
    const nextTags = Array.from(nextUnique.values());
    const nextDesc = isAutoGeneratedDescription(tx.description)
      ? tx.description
      : nextTags.join(", ");

    const { error } = await supabase
      .from("transactions")
      .update({ tags: nextTags, description: nextDesc })
      .eq("id", tx.id);

    if (error) {
      // Fallback if `tags` column hasn't been added yet
      if (/column .*tags/i.test(error.message) || /'tags' column/i.test(error.message)) {
        const { error: err2 } = await supabase
          .from("transactions")
          .update({ description: nextDesc })
          .eq("id", tx.id);
        if (err2) throw new Error(err2.message);
      } else {
        throw new Error(error.message);
      }
    }
    updatedCount++;
  }

  return updatedCount;
};

/**
 * Cleans legacy "Gasto rápido: " prefixes across existing transactions.
 * Keeps meaningful tags like "Café" in Bar/Restaurante, clears redundant ones like "compra" in Supermercado or "Tabaco" in tabaco.
 */
export const cleanupQuickExpensePrefixesInCloud = async (
  transactions: Transaction[]
): Promise<{ cleaned: number; keptTags: number; clearedRedundant: number }> => {
  const targets = transactions.filter((t) => hasQuickExpensePrefix(t.description));
  let cleaned = 0;
  let keptTags = 0;
  let clearedRedundant = 0;

  for (const tx of targets) {
    const stripped = stripQuickExpensePrefix(tx.description);
    const norm = normalizeTagKey(stripped);
    const redundant = isRedundantWithCategory(norm, tx.category);

    const nextTags = redundant ? [] : [formatTagDisplay(stripped)];
    const nextDesc = redundant ? "" : formatTagDisplay(stripped);

    const { error } = await supabase
      .from("transactions")
      .update({ tags: nextTags, description: nextDesc })
      .eq("id", tx.id);

    if (error) {
      if (/column .*tags/i.test(error.message) || /'tags' column/i.test(error.message)) {
        const { error: err2 } = await supabase
          .from("transactions")
          .update({ description: nextDesc })
          .eq("id", tx.id);
        if (err2) throw new Error(err2.message);
      } else {
        throw new Error(error.message);
      }
    }

    cleaned++;
    if (redundant) clearedRedundant++;
    else keptTags++;
  }

  return { cleaned, keptTags, clearedRedundant };
};
